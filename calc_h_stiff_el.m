function M_h_el = calc_h_stiff_el(el_ylen,el_xlen);
% CALC_H_STIFF_EL defines element stiffness matrix without K
% version 20 june 2001 WN

% analytical solution for rectangular bilinear element, constant K
% LOCAL POINT INDEXING SYSTEM (elementwise)
%               1 3
%               2 4
% M_el contains the following nodal connections:
%  11 12 13 14
%  21 22 23 24
%  31 32 33 34
%  41 42 43 44

M_h_el  = el_ylen/el_xlen/6*  ...
        [+2 +1 -2 -1; ...
         +1 +2 -1 -2; ...
         -2 -1 +2 +1; ...
         -1 -2 +1 +2];
M_h_el  = M_h_el + el_xlen/el_ylen/6* ...
        [+2 -2 +1 -1; ...
         -2 +2 -1 +1; ...
         +1 -1 +2 -2; ...
         -1 +1 -2 +2];